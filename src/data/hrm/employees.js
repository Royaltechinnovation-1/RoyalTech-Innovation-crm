/** @param {string} d dd/mm/yyyy or messy variants → yyyy-mm-dd */
function dmy(d) {
  if (!d || !String(d).trim()) return "";
  const parts = String(d).trim().split(/[\/\-]/);
  if (parts.length !== 3) return "";
  let [dd, mm, yy] = parts;
  if (yy.length === 2) yy = `20${yy}`;
  if (yy.length === 3) yy = `2${yy}`; // e.g. 026 → 2026
  const y = yy.padStart(4, "0");
  const m = mm.padStart(2, "0");
  const day = dd.padStart(2, "0");
  // fix obvious typos like 30/20/2026
  const monthNum = Number(m);
  const safeM = monthNum > 12 ? "10" : m;
  return `${y}-${safeM}-${day}`;
}

function yn(v) {
  if (v == null || v === "") return "";
  const s = String(v).trim().toLowerCase();
  if (["yes", "y"].includes(s)) return "Yes";
  if (["no", "n"].includes(s)) return "No";
  return String(v).trim();
}

function cleanId(v) {
  return String(v || "").trim().replace(/_/g, "-");
}

function salaryNum(v) {
  if (v == null || v === "") return 0;
  const m = String(v).replace(/,/g, "").match(/[\d.]+/);
  return m ? Number(m[0]) : 0;
}

function companyMail(name) {
  const slug = String(name || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, "")
    .split(/\s+/)
    .filter(Boolean)
    .join(".");
  return slug ? `${slug}@ryaltehinno.in` : "";
}

function emp(row) {
  const salary = salaryNum(row.monthlySalary);
  const docs = {
    experienceLetter: yn(row.experienceLetter),
    relievingLetter: yn(row.relievingLetter),
    lastSalarySlip: yn(row.lastSalarySlip),
    pfUan: yn(row.pfUan),
    aadhaar: yn(row.aadhaar),
    aadhaarNumber: String(row.aadhaarNumber || "").replace(/\s+/g, " ").trim(),
    pan: yn(row.pan),
    panNumber: String(row.panNumber || "").trim(),
    bankDetails: yn(row.bankDetails),
    education: yn(row.education),
    passportPhotos: yn(row.passportPhotos),
    other: String(row.otherDocuments || "").trim(),
    complete: yn(row.documentsComplete),
  };

  const id = cleanId(row.id);
  const numFromId = Number(String(id).replace(/\D/g, "")) || 0;
  // Unique staff UID — not the calendar year (e.g. 2026)
  const uid = row.uid ?? 11000 + numFromId;
  // Office entry / access card number (unique per employee)
  const cardNumber = row.cardNumber || `RT${String(9801000 + numFromId).padStart(7, "0")}`;

  return {
    id,
    uid,
    cardNumber,
    name: row.name,
    email: row.email || "",
    companyEmail: row.companyEmail || companyMail(row.name),
    phone: row.phone || "",
    department: row.department,
    designation: row.designation,
    joiningDate: dmy(row.joiningDate),
    status: row.status === "Employeed" || row.status === "Employed" ? "Active" : row.status || "Active",
    employmentType: row.employmentType || "Full-time",
    location: row.location || "Mohali",
    manager: row.manager || "CEO (Shreya)",
    dob: "",
    gender: "",
    salary,
    skills: [],
    address: row.location || "Mohali",
    emergency: { name: "", relation: "", phone: "" },
    about: row.salaryNotes || "",
    // RoyalTech joining tracker fields
    interviewDate: dmy(row.interviewDate),
    selectionDate: dmy(row.selectionDate),
    offerLetterSent: dmy(row.offerLetterSent),
    offerLetterEmailDate: dmy(row.offerLetterEmailDate),
    offerAccepted: yn(row.offerAccepted),
    probationPeriod: row.probationPeriod || "3 Months",
    previousCompany: row.previousCompany || "",
    totalExperience: row.totalExperience || "",
    lastWorkingDay: dmy(row.lastWorkingDay),
    salaryNotes: row.salaryNotes || "IN Hand no deduction",
    documents: docs,
    joiningEmailSent: yn(row.joiningEmailSent),
    joiningEmailDate: dmy(row.joiningEmailDate),
    welcomeOnboardingCompleted: yn(row.welcomeOnboarding),
    companyAccessProvided: yn(row.companyAccess),
    notes: row.notes || "",
  };
}

